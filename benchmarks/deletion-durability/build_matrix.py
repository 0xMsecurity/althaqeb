#!/usr/bin/env python3
"""build_matrix — validate the deletion-durability registry and render the comparison matrix.

This is the integrity gate for the registry. It enforces the constitution's NO FAKE RESULTS
rule structurally:

  * every entry must carry the required fields with correct types;
  * every cited evidence path must EXIST as a committed file (build FAILS otherwise);
  * any entry claiming confidence high/medium with NO evidence is a FAIL;
  * entries with confidence low/unverified are allowed but reported as evidence gaps (WARN).

No third-party dependencies (stdlib only) — deterministic, reproducible, one-year-survivable.

Usage:
  build_matrix.py            validate, then (re)write MATRIX.md
  build_matrix.py --check    validate only, write nothing (CI gate)

Exit: 0 = valid, 2 = integrity failure (missing evidence / schema violation).
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
REGISTRY = os.path.join(HERE, "registry.json")
MATRIX = os.path.join(HERE, "MATRIX.md")

REQUIRED = {
    "engine": str, "version": str, "category": str,
    "residue_after_delete": bool, "recovery_method": str,
    "self_identifying_deletion": bool, "reclamation_trigger": str,
    "window_class": str, "measured": list, "evidence": list, "confidence": str,
}
WINDOW_CLASSES = {"unbounded", "auto-timed", "auto-untimed", "manual-only", "none"}
CONFIDENCES = {"high", "medium", "low", "unverified"}


def validate(reg):
    """Return (errors, warnings). errors are fatal (exit 2)."""
    errors, warnings = [], []
    engines = reg.get("engines")
    if not isinstance(engines, list) or not engines:
        return ["registry has no 'engines' list"], []
    seen = set()
    for i, e in enumerate(engines):
        tag = e.get("engine", f"#{i}")
        for field, typ in REQUIRED.items():
            if field not in e:
                errors.append(f"[{tag}] missing field '{field}'"); continue
            if not isinstance(e[field], typ):
                errors.append(f"[{tag}] field '{field}' must be {typ.__name__}")
        if tag in seen:
            errors.append(f"[{tag}] duplicate engine name")
        seen.add(tag)
        if e.get("window_class") not in WINDOW_CLASSES:
            errors.append(f"[{tag}] window_class '{e.get('window_class')}' not in {sorted(WINDOW_CLASSES)}")
        conf = e.get("confidence")
        if conf not in CONFIDENCES:
            errors.append(f"[{tag}] confidence '{conf}' not in {sorted(CONFIDENCES)}")
        # evidence files must exist (this is the NO FAKE RESULTS gate)
        for ev in e.get("evidence", []):
            if not os.path.isfile(os.path.join(REPO_ROOT, ev)):
                errors.append(f"[{tag}] cited evidence missing on disk: {ev}")
        # confidence vs evidence policy
        if conf in {"high", "medium"} and not e.get("evidence"):
            errors.append(f"[{tag}] confidence '{conf}' but no evidence files cited")
        if conf in {"low", "unverified"}:
            warnings.append(f"[{tag}] evidence gap (confidence={conf}): {e.get('notes','')}")
    return errors, warnings


def render(reg):
    order = {"unbounded": 0, "auto-untimed": 1, "manual-only": 2, "auto-timed": 3, "none": 4}
    engines = sorted(reg["engines"],
                     key=lambda e: (order.get(e["window_class"], 9),
                                    e.get("window_seconds") if e.get("window_seconds") is not None else -1))
    L = []
    L.append("# Vector Database Deletion-Durability Matrix")
    L.append("")
    L.append("> GENERATED by `build_matrix.py` from `registry.json` — do not edit by hand.")
    L.append("> Every row's claims trace to committed result files; the build fails if any are missing.")
    L.append("")
    L.append(f"**{reg['name']} v{reg['version']}**")
    L.append("")
    L.append(reg["description"])
    L.append("")
    L.append("## Method")
    L.append("")
    L.append(reg["method_summary"])
    L.append("")
    L.append("## Matrix")
    L.append("")
    L.append("| Engine | Residue after delete? | Self-ID'd by deletion | Reclamation trigger | Window class | Measured window | Confidence |")
    L.append("|---|---|---|---|---|---|---|")
    for e in engines:
        residue = "**YES**" if e["residue_after_delete"] else "no (true negative)"
        selfid = "yes" if e["self_identifying_deletion"] else "—"
        ws = e.get("window_seconds")
        win = f"~{ws}s" if ws is not None else ("unbounded" if e["window_class"] == "unbounded" else "—")
        L.append(f"| **{e['engine']}** ({e['version']}) | {residue} | {selfid} | {e['reclamation_trigger']} "
                 f"| {e['window_class']} | {win} | {e['confidence']} |")
    L.append("")
    L.append("## Window-class taxonomy")
    L.append("")
    for k, v in reg["window_class_values"].items():
        L.append(f"- **{k}** — {v}")
    L.append("")
    L.append("## Per-engine evidence")
    L.append("")
    for e in engines:
        L.append(f"### {e['engine']} ({e['version']})")
        L.append(f"- category: {e['category']}")
        L.append(f"- recovery method: {e['recovery_method']}")
        if e.get("window_note"):
            L.append(f"- window: {e['window_note']}")
        if e.get("notes"):
            L.append(f"- note: {e['notes']}")
        L.append("- measured:")
        for m in e["measured"]:
            L.append(f"  - {m}")
        L.append("- evidence (committed result files):")
        if e["evidence"]:
            for ev in e["evidence"]:
                L.append(f"  - `{ev}`")
        else:
            L.append("  - **none committed — evidence gap**")
        L.append("")
    return "\n".join(L) + "\n"


def main():
    check_only = "--check" in sys.argv[1:]
    reg = json.load(open(REGISTRY))
    errors, warnings = validate(reg)
    for w in warnings:
        print(f"WARN  {w}")
    if errors:
        for er in errors:
            print(f"FAIL  {er}")
        print(f"\n[FAIL] {len(errors)} integrity error(s); matrix not written.")
        return 2
    n = len(reg["engines"])
    leak = sum(1 for e in reg["engines"] if e["residue_after_delete"])
    print(f"[OK] {n} engines validated, {leak} leak a post-delete recovery window, "
          f"{len(warnings)} evidence gap(s).")
    if not check_only:
        open(MATRIX, "w").write(render(reg))
        print(f"[OK] wrote {os.path.relpath(MATRIX, REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
